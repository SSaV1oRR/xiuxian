// READY 整体前移 z（根运动累计到 z 时的收势姿势：脚位按地面参照一并前移）
const readyAt = (z) => ({ ...clone(READY), root: z, fR: [READY.fR[0], READY.fR[1], READY.fR[2] + z], fL: [READY.fL[0], READY.fL[1], READY.fL[2] + z] });
// 一段动作在某一键时的完整姿势（缺省项沿用前面的键）
function merged(keys, i) {
  let o = {};
  for (let k = 0; k <= i; k++) o = { ...o, ...keys[k], R: keys[k].R ? { ...(o.R || {}), ...keys[k].R } : o.R };
  return clone(o);
}
// 接招：把上一段某一键的姿势换成新一段的起点（根运动归零，脚位减去已走的根运动）
function rebase(keys, i) {
  const o = merged(keys, i), z = o.root || 0;
  o.root = 0; o.fR = [o.fR[0], o.fR[1], o.fR[2] - z]; o.fL = [o.fL[0], o.fL[1], o.fL[2] - z];
  delete o.t; delete o.ease;
  return o;
}

