// 生成：返回 { clips: AnimationClip[], report: { 名字: 检查结果 } }
export function buildCultivatorClips(char, { only = null, Pose = CultivatorPose } = {}) {
  const S = new Pose(char);
  const clips = [], report = {};
  for (const [name, def] of Object.entries(CLIP_DEFS)) {
    if (only && !only.includes(name)) continue;
    const c = S.clip(name, def.keys, { loop: !!def.loop, marks: def.marks || {}, fps: def.fps || 30 });
    clips.push(c); report[name] = c.userData.check;
  }
  return { clips, report };
}
