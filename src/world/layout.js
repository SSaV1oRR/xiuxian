// 叠落廊的分段：n 段、每段长 bay；land 中的段为平台段（不升高，可在侧面开门通台地），其余段首设踏步
export function corridorPlan(st) {
  const [zb, yb] = st.bottom, [zt, yt] = st.top, L = zb - zt, rise = yt - yb;
  const n = Math.max(2, Math.round(L / 3.3)), bay = L / n, land = st.land || [];
  const steps = n - 1 - land.filter((i) => i > 0 && i < n).length, dh = rise / steps;
  const floors = [0];
  for (let i = 1; i < n; i++) floors.push(floors[i - 1] + (land.includes(i) ? 0 : dh));
  const ns = Math.max(1, Math.ceil(dh / 0.2)), run = Math.min(0.32, (bay * 0.78) / ns), Ls = ns * run;
  return { n, bay, dh, floors, ns, run, Ls, L, rise, yb, zb, land, open: st.open || [] };
}
