// 崖线的平面折线：转角按圆角（切线长不超过 fillet）过渡，再按 ds 等距重采样；n 为左法线（指向谷）
export function cliffLine(run, ds = 0.6) {
  const closed = !!run.closed;
  const P0 = closed ? pillarPts(run) : run.pts, R = run.fillet ?? (closed ? 3 : 4);
  // 闭合折线：首尾各补一个相邻点，转角圆角绕一整圈，最后回到起点
  const P = closed ? [P0[P0.length - 1], ...P0, P0[0], P0[1]] : P0;
  const pts = closed ? [] : [P[0]];
  for (let i = 1; i < P.length - 1; i++) {
    if (closed && i === P.length - 2) break;
    const [ax, az] = P[i - 1], [bx, bz] = P[i], [cx, cz] = P[i + 1];
    const l1 = Math.hypot(bx - ax, bz - az), l2 = Math.hypot(cx - bx, cz - bz);
    const u1x = (bx - ax) / l1, u1z = (bz - az) / l1, u2x = (cx - bx) / l2, u2z = (cz - bz) / l2;
    const th = Math.acos(Math.max(-1, Math.min(1, u1x * u2x + u1z * u2z)));
    if (th < 0.04) { pts.push(P[i]); continue; }
    const t = Math.min(R, 0.45 * Math.min(l1, l2)), n = Math.max(2, Math.ceil((th * t) / 0.5));
    const p1x = bx - u1x * t, p1z = bz - u1z * t, p2x = bx + u2x * t, p2z = bz + u2z * t;
    for (let k = 0; k <= n; k++) { const s = k / n, a = (1 - s) * (1 - s), b = 2 * s * (1 - s), c = s * s; pts.push([a * p1x + b * bx + c * p2x, a * p1z + b * bz + c * p2z]); }
  }
  if (closed) pts.push(pts[0]); else pts.push(P[P.length - 1]);
  const cum = [0];
  for (let i = 1; i < pts.length; i++) cum.push(cum[i - 1] + Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]));
  const L = cum[cum.length - 1], N = Math.max(2, Math.round(L / ds) + 1);
  const x = new Float32Array(N), z = new Float32Array(N), s = new Float32Array(N), nx = new Float32Array(N), nz = new Float32Array(N);
  let j = 0;
  for (let i = 0; i < N; i++) {
    const t = (L * i) / (N - 1);
    while (j < cum.length - 2 && cum[j + 1] < t) j++;
    const u = (t - cum[j]) / (cum[j + 1] - cum[j] || 1);
    x[i] = pts[j][0] + (pts[j + 1][0] - pts[j][0]) * u; z[i] = pts[j][1] + (pts[j + 1][1] - pts[j][1]) * u; s[i] = t;
  }
  for (let i = 0; i < N; i++) {
    let a = Math.max(0, i - 1), b = Math.min(N - 1, i + 1);
    if (closed && i === 0) a = N - 2;
    if (closed && i === N - 1) b = 1;
    const dx = x[b] - x[a], dz = z[b] - z[a], l = Math.hypot(dx, dz) || 1;
    nx[i] = dz / l; nz[i] = -dx / l;
  }
  return { x, z, s, nx, nz, N, L, ds: L / (N - 1), closed };
}

